#!/usr/bin/env python3
"""Emit the supplementary table the previous drafts never carried: the complete product
structures of the frozen Library 0 panel.

Both the ICLR and Nature Biotechnology supplements give every *component* SMILES across Tables
S10--S12, but neither prints the final product SMILES of the forty candidates. A reader therefore
cannot reconstruct which molecules were actually proposed, which is a strange omission for a paper
whose claim is that it generates novel chemistry. The structures exist in the frozen panel as
`canonical_product`; this script lifts them into a table.

Provenance only. This does not rank, reselect, or rescore anything. `lcb90` and the authority tier
are deliberately NOT emitted: they belong to the pilot's ranking rule rather than the current one,
and reprinting them beside the structures would invite reading them as current. Selection order
within arm is emitted because it is what the frozen rule produced and is needed to audit it.
"""

from __future__ import annotations

import argparse
import gzip
import hashlib
import json
import platform
import sys
import time
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
PANEL = "results/phase1/ugi_prospective_panel_v6/prospective_panel.jsonl.gz"


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def load(path: Path) -> list[dict]:
    with gzip.open(path, "rt") as handle:
        return [json.loads(line) for line in handle if line.strip()]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output", type=Path,
        default=REPO / "results/phase1/forge_product_structure_table_v1/table.md")
    args = parser.parse_args()
    started = time.time()

    panel_path = REPO / PANEL
    rows = load(panel_path)
    if len(rows) != 40:
        raise SystemExit(f"expected the frozen 40, found {len(rows)}")

    # Sort by arm then the frozen selection order, so the table reproduces the rule's own output
    # rather than imposing a new order.
    rows.sort(key=lambda r: (r["arm"] != "HIGH", int(r["selection_order_within_arm"])))

    lines = [
        "## Table S17 | Complete product structures of the frozen panel",
        "",
        "Every candidate in the frozen Library 0 pilot, with its generated product structure and the "
        "three components that assemble it. Structures are canonical non-isomeric SMILES: generation "
        "is constitutional, so no stereochemistry is proposed. `Novel` marks absence from the "
        f"{'12,276'}-product enumerated library. Predicted activity, the pilot's calibrated lower "
        "bound and the authority tier are deliberately omitted; this table documents which molecules "
        "were proposed, not how they were ranked.",
        "",
        "| ID | Arm | Steps | Route complete | Novel vs library | Product SMILES |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows:
        novel = r["novelty"].get("absent_from_agile_library")
        lines.append(
            f"| {r['candidate_id']} | {r['arm']} | {r['synthetic_steps']} | "
            f"{'yes' if r['route_complete'] else 'no'} | {'yes' if novel else 'no'} | "
            f"`{r['canonical_product']}` |")

    lines += ["", "### Components per candidate", "",
              "| ID | Amine head | Aldehyde tail | Isocyanide tail |", "|---|---|---|---|"]
    for r in rows:
        c = r["components"]
        lines.append(
            f"| {r['candidate_id']} | `{c['amine_head']}` | "
            f"`{c['oxoester_aldehyde_body_tail']}` | `{c['isocyanide_tail']}` |")

    distinct_products = len({r["canonical_product"] for r in rows})
    stereo = [r["candidate_id"] for r in rows if "@" in r["canonical_product"]]
    high = sum(1 for r in rows if r["arm"] == "HIGH")

    lines += [
        "",
        f"All {len(rows)} products are constitutionally distinct ({distinct_products} unique "
        f"canonical SMILES). {high} are high-ranked designs and {len(rows) - high} are low-ranked "
        "controls. No member has been synthesized.",
    ]
    if stereo:
        raise SystemExit(f"stereochemistry present in a generated product: {stereo}")

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines) + "\n")

    # LaTeX form, \input by the manuscript so the table lands in the PDF instead of sitting in a
    # results directory. longtable because forty rows plus components will not fit one page.
    # SMILES are up to 67 characters, so \ttfamily\scriptsize inside a p-column that wraps.
    tex = [
        r"% autogenerated table, regenerate dont edit",
        r"\begingroup\scriptsize",
        r"\setlength{\LTcapwidth}{\textwidth}",
        r"\begin{longtable}{@{}llccl@{}}",
        r"\caption{\textbf{Product structures of the frozen Library~0 pilot.} Canonical non-isomeric "
        r"SMILES; generation is constitutional and proposes no stereochemistry. \emph{Novel} marks "
        r"absence from the enumerated reference library. Predicted activity and the pilot's "
        r"calibrated bound are omitted, since this table records which molecules were proposed "
        r"rather than how they were ranked. No member has been synthesized."
        r"}\label{tab:products}\\",
        r"\toprule",
        r"ID & Arm & Steps & Novel & Product SMILES \\",
        r"\midrule",
        r"\endfirsthead",
        r"\toprule ID & Arm & Steps & Novel & Product SMILES \\ \midrule \endhead",
        r"\bottomrule",
        r"\endfoot",
    ]
    for r in rows:
        novel = "yes" if r["novelty"].get("absent_from_agile_library") else "no"
        smiles = r["canonical_product"].replace("=", r"{=}").replace("#", r"\#")
        tex.append(
            f"{r['candidate_id']} & {r['arm']} & {r['synthetic_steps']} & {novel} & "
            f"\\texttt{{{smiles}}} \\\\")
    tex += [r"\end{longtable}", r"\endgroup", ""]

    # Components, as a second generated table.
    tex += [
        r"\begingroup\scriptsize",
        r"\begin{longtable}{@{}llll@{}}",
        r"\caption{\textbf{Components of every frozen candidate.} Each product is assembled from "
        r"exactly these three precursor-derived graphs under the qualified forward Ugi transform."
        r"}\label{tab:components}\\",
        r"\toprule",
        r"ID & Amine head & Aldehyde tail & Isocyanide tail \\",
        r"\midrule",
        r"\endfirsthead",
        r"\toprule ID & Amine head & Aldehyde tail & Isocyanide tail \\ \midrule \endhead",
        r"\bottomrule",
        r"\endfoot",
    ]

    def esc(value: str) -> str:
        return value.replace("=", r"{=}").replace("#", r"\#")

    for r in rows:
        c = r["components"]
        tex.append(
            f"{r['candidate_id']} & \\texttt{{{esc(c['amine_head'])}}} & "
            f"\\texttt{{{esc(c['oxoester_aldehyde_body_tail'])}}} & "
            f"\\texttt{{{esc(c['isocyanide_tail'])}}} \\\\")
    tex += [r"\end{longtable}", r"\endgroup", ""]

    tex_path = REPO / "paper" / "generated_product_structures.tex"
    tex_path.write_text("\n".join(tex) + "\n")
    print(f"wrote {tex_path.relative_to(REPO)}")

    meta = {
        "schema_version": "phase1_forge_product_structure_table.v1",
        "status": "complete",
        "purpose": "supplementary table of complete product structures, absent from both prior drafts",
        "inputs": {"panel": {"path": PANEL, "sha256": sha256_file(panel_path)}},
        "runtime": {"python_version": platform.python_version(),
                    "platform": platform.platform(),
                    "elapsed_seconds": round(time.time() - started, 1)},
        "rows": len(rows),
        "distinct_canonical_products": distinct_products,
        "high_arm": high,
        "low_arm": len(rows) - high,
        "omitted_deliberately": {
            "lcb90": "the pilot's ranking statistic, provenance only, not reprinted beside structures",
            "authority_tier": "tier machinery not used as ranking authority in the current formulation",
            "oracle_mean": "predicted activity is not printed with the structures",
        },
        "nonclaims": [
            "No member of this panel has been synthesized.",
            "Route completeness is computational and is not evidence any reaction will succeed.",
            "This table does not rank, reselect or rescore any candidate.",
        ],
    }
    meta_path = args.output.parent / "result.json"
    meta_path.write_text(json.dumps(meta, indent=1, sort_keys=True))

    print(f"wrote {args.output.relative_to(REPO)}")
    print(f"wrote {meta_path.relative_to(REPO)}")
    print(f"{len(rows)} candidates, {distinct_products} distinct products, "
          f"{high} high / {len(rows) - high} low, no stereochemistry")


if __name__ == "__main__":
    main()
